function normalizeProfileName(name) {
  return (name || "")
    .trim()
    .replace(/（/g, "(")
    .replace(/）/g, ")")
    .replace(/\u3000/g, " ")
    .replace(/\s+/g, " ");
}

function foldSearchText(value) {
  return normalizeProfileName(value)
    .replace(/[\u2018\u2019'`´]/g, "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

function getProfileByName(name) {
  if (PROFILE_DATA[name]) return PROFILE_DATA[name];
  const folded = foldSearchText(name);
  const match = Object.entries(PROFILE_DATA).find(([key, profile]) => {
    if (foldSearchText(key) === folded) return true;
    const aliases = Array.isArray(profile?.searchAliases) ? profile.searchAliases : [];
    return aliases.some((alias) => foldSearchText(alias) === folded);
  });
  return match ? match[1] : null;
}

function getCanonicalProfileName(name) {
  if (PROFILE_DATA[name]) return name;
  const folded = foldSearchText(name);
  const match = Object.entries(PROFILE_DATA).find(([key, profile]) => {
    if (foldSearchText(key) === folded) return true;
    const aliases = Array.isArray(profile?.searchAliases) ? profile.searchAliases : [];
    return aliases.some((alias) => foldSearchText(alias) === folded);
  });
  return match ? match[0] : name;
}

